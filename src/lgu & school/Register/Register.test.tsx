import { fireEvent, render, screen } from '@testing-library/react';
import { MemoryRouter, Route, Routes } from 'react-router-dom';
import { beforeEach, expect, it, vi } from 'vitest';
import Register from './Register';
const mocks = vi.hoisted(() => ({ create: vi.fn(), save: vi.fn(), send: vi.fn() }));
vi.mock('firebase/auth', () => ({ createUserWithEmailAndPassword: mocks.create, deleteUser: vi.fn() }));
vi.mock('firebase/firestore', () => ({ setDoc: mocks.save, doc: vi.fn(), serverTimestamp: vi.fn() }));
vi.mock('../../Firebase/config', () => ({ auth: {}, db: {} }));
vi.mock('../../services/emailVerificationService', () => ({ sendVerificationEmail: mocks.send }));
beforeEach(() => { vi.stubGlobal('scrollTo', vi.fn()); vi.clearAllMocks(); mocks.create.mockResolvedValue({ user: { uid: 'org1' } }); });
it('completes organization registration with a verification link and Firestore profile', async () => {
  render(<MemoryRouter initialEntries={['/lgu-register']}><Routes><Route path="/lgu-register" element={<Register />} /><Route path="/verify-email" element={<h1>Verify account email</h1>} /></Routes></MemoryRouter>);
  fireEvent.change(screen.getByPlaceholderText('organization@example.com'), { target: { value: 'school@example.com' } });
  fireEvent.click(screen.getByText('Continue'));
  fireEvent.change(screen.getByPlaceholderText('Create a password'), { target: { value: 'Password123!' } });
  fireEvent.change(screen.getByPlaceholderText('Re-enter your password'), { target: { value: 'Password123!' } });
  fireEvent.click(screen.getByText('Continue'));
  fireEvent.click(screen.getByText('School', { selector: 'strong' }));
  fireEvent.change(screen.getByPlaceholderText('Enter official organization name'), { target: { value: 'Test School' } });
  fireEvent.change(screen.getByPlaceholderText('Street, barangay, municipality, province'), { target: { value: 'Manila' } });
  fireEvent.change(screen.getByPlaceholderText('e.g. 09123456789'), { target: { value: '09123456789' } });
  fireEvent.click(screen.getByText('Continue'));
  fireEvent.change(screen.getByPlaceholderText('Enter full name'), { target: { value: 'Coordinator' } });
  fireEvent.change(screen.getByPlaceholderText('e.g. Scholarship Coordinator'), { target: { value: 'Coordinator' } });
  fireEvent.click(screen.getByRole('checkbox'));
  fireEvent.click(screen.getByText('Submit Registration'));
  expect(await screen.findByText('Verify account email')).toBeTruthy();
  expect(mocks.create).toHaveBeenCalledWith({}, 'school@example.com', 'Password123!');
  expect(mocks.save.mock.calls[0][1]).toMatchObject({ role: 'lgu_school', emailVerified: false, organizationName: 'Test School' });
  expect(mocks.send).toHaveBeenCalledWith({ uid: 'org1' });
});
